export function isDisposableEmailDomain(domain) {
  if (!domain) return false;
  const clean = String(domain).trim().toLowerCase();
  if (DISPOSABLE_EMAIL_DOMAINS.has(clean)) return true;
  // Also check parent domain for subdomains of disposable providers (e.g. sub.mailinator.com)
  const parts = clean.split('.');
  if (parts.length > 2) {
    const rootDomain = parts.slice(-2).join('.');
    if (DISPOSABLE_EMAIL_DOMAINS.has(rootDomain)) return true;
  }
  return false;
}
